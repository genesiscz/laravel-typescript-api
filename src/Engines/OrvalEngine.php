<?php

namespace Genesiscz\LaravelTypescriptApi\Engines;

use Genesiscz\LaravelTypescriptApi\Contracts\Engine;
use Genesiscz\LaravelTypescriptApi\Pipeline\GenerateContext;
use Illuminate\Support\Facades\File;

/**
 * openapi.json → Orval. Writes a temporary orval.config.ts from the
 * first-class options + passthrough, then `bunx orval --config <config>`.
 */
class OrvalEngine implements Engine
{
    public function name(): string
    {
        return 'orval';
    }

    public function generate(GenerateContext $context, array $options): void
    {
        $outputDir = $context->enginePath($this);
        File::ensureDirectoryExists($outputDir);

        $configPath = $this->writeConfig($context, $options, $outputDir);

        try {
            $context->runner->run('orval', ['--config', $configPath]);
        } finally {
            File::delete($configPath);
        }

        foreach (File::allFiles($outputDir) as $file) {
            $context->trackFile($file->getPathname());
        }
    }

    protected function writeConfig(GenerateContext $context, array $options, string $outputDir): string
    {
        $output = array_replace_recursive([
            'mode' => $options['mode'] ?? 'tags-split',
            'target' => $outputDir,
            'client' => $options['client'] ?? 'react-query',
            'httpClient' => $options['httpClient'] ?? 'fetch',
            'mock' => $options['mock'] ?? false,
            'override' => array_filter([
                'mutator' => $options['mutator'] ?? null,
                'query' => $options['query'] ?? null,
            ]),
        ], $options['passthrough'] ?? []);

        $config = [
            'api' => [
                'input' => ['target' => $context->artifactPath],
                'output' => $output,
            ],
        ];

        $path = $outputDir.'/.orval.config.ts';

        File::put($path, sprintf(
            "// Generated by laravel-typescript-api — do not edit.\nimport { defineConfig } from 'orval';\n\nexport default defineConfig(%s);\n",
            json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
        ));

        return $path;
    }
}
