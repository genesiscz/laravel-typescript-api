<?php

namespace Genesiscz\LaravelTypescriptApi\Engines;

use Genesiscz\LaravelTypescriptApi\Contracts\Engine;
use Genesiscz\LaravelTypescriptApi\Pipeline\GenerateContext;
use Illuminate\Support\Facades\File;

/**
 * openapi.json → @hey-api/openapi-ts. Writes a temporary
 * openapi-ts.config.ts from the configured plugins + passthrough, then
 * `bunx @hey-api/openapi-ts -f <config>`.
 */
class HeyApiEngine implements Engine
{
    public function name(): string
    {
        return 'hey-api';
    }

    public function generate(GenerateContext $context, array $options): void
    {
        $outputDir = $context->enginePath($this);
        File::ensureDirectoryExists($outputDir);

        $configPath = $this->writeConfig($context, $options, $outputDir);

        try {
            $context->runner->run(
                ['@hey-api/openapi-ts' => '^0.99', 'typescript' => '^5.5'],
                'openapi-ts',
                ['-f', $configPath],
            );
        } finally {
            File::delete($configPath);
        }

        foreach (File::allFiles($outputDir) as $file) {
            $context->trackFile($file->getPathname());
        }
    }

    protected function writeConfig(GenerateContext $context, array $options, string $outputDir): string
    {
        $config = array_replace_recursive([
            'input' => $context->artifactPath,
            'output' => [
                'path' => $outputDir,
            ],
            'plugins' => $this->plugins($options),
        ], $options['passthrough'] ?? []);

        $path = $outputDir.'/.openapi-ts.config.ts';

        File::put($path, sprintf(
            "// Generated by laravel-typescript-api — do not edit.\nexport default %s;\n",
            json_encode($config, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
        ));

        return $path;
    }

    protected function plugins(array $options): array
    {
        $plugins = $options['plugins'] ?? ['@hey-api/typescript', '@hey-api/sdk', '@tanstack/react-query'];

        if (isset($options['client'])) {
            array_unshift($plugins, $options['client']);
        }

        // Normalize [name => opts] entries to hey-api's {name, ...opts} form.
        return collect($plugins)
            ->map(fn ($value, $key) => is_string($key)
                ? array_merge(['name' => $key], (array) $value)
                : $value)
            ->values()
            ->all();
    }
}
