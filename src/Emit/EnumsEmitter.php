<?php

namespace Genesiscz\LaravelTypescriptApi\Emit;

use Genesiscz\LaravelTypescriptApi\Contracts\Emitter;
use Genesiscz\LaravelTypescriptApi\Pipeline\GenerateContext;
use Illuminate\Support\Facades\File;

/**
 * Authoritative enums.ts from the OpenAPI document's enum schemas —
 * x-enum-varnames (PHP case names, stamped via scramble's
 * enum_cases_names_strategy 'varnames') become member names, so output
 * matches the PHP enums verbatim (ReservineBack enums.ts parity).
 *
 * options.style: 'enum' (real TS enum) | 'const' (as-const object) | 'union'.
 */
class EnumsEmitter implements Emitter
{
    public function emit(GenerateContext $context, array $options): void
    {
        $style = $options['style'] ?? 'enum';
        $file = $options['file'] ?? 'enums.ts';

        $blocks = [];

        foreach ($context->openapi['components']['schemas'] ?? [] as $name => $schema) {
            $values = $schema['enum'] ?? null;

            if (! is_array($values) || $values === []) {
                continue;
            }

            $names = $schema['x-enum-varnames']
                ?? $schema['x-enumNames']
                ?? array_map(fn ($value) => $this->memberName($value), $values);

            $blocks[$name] = $this->renderEnum($name, array_combine($names, $values), $style);
        }

        if ($blocks === []) {
            return;
        }

        ksort($blocks);

        $dir = $options['path'] ?? $context->outputPath;
        File::ensureDirectoryExists($dir);

        $path = rtrim($dir, '/').'/'.$file;

        File::put($path, "// Generated by laravel-typescript-api — do not edit.\n\n".implode("\n", $blocks));
        $context->trackFile($path);
    }

    /** @param array<string, int|string> $members */
    protected function renderEnum(string $name, array $members, string $style): string
    {
        $lines = [];

        foreach ($members as $member => $value) {
            $lines[] = "\t{$member} = ".$this->literal($value).',';
        }

        $body = implode("\n", $lines);

        return match ($style) {
            'const' => "export const {$name} = {\n".implode("\n", array_map(
                fn ($member, $value) => "\t{$member}: ".$this->literal($value).',',
                array_keys($members),
                $members,
            ))."\n} as const;\nexport type {$name} = (typeof {$name})[keyof typeof {$name}];\n",
            'union' => "export type {$name} = ".implode(' | ', array_map(
                fn ($value) => $this->literal($value),
                $members,
            )).";\n",
            default => "export enum {$name} {\n{$body}\n}\n",
        };
    }

    protected function literal(int|string $value): string
    {
        return is_int($value) ? (string) $value : "\"{$value}\"";
    }

    protected function memberName(int|string $value): string
    {
        $name = preg_replace('/[^A-Za-z0-9]+/', '_', (string) $value) ?? (string) $value;

        return preg_match('/^\d/', $name) ? "_{$name}" : $name;
    }
}
